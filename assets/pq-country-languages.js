const byCountry = new Map(groups.flatMap(([languages, countries]) =>
  countries.split(' ').map(country => [country, languages.toLowerCase().split(' ')])
));

export function languageForCountry(country, available) {
  const codes = available.filter(Boolean);
  const normalized = new Map(codes.map(code => [code.toLowerCase(), code]));
  const candidates = byCountry.get(country) ?? [];

  for (const language of [...candidates, 'en']) {
    if (normalized.has(language)) return normalized.get(language);
    const base = language.split('-')[0];
    if (normalized.has(base)) return normalized.get(base);
    // Keep explicit regional/script variants distinct when only the other variant is published.
    if (language === base) {
      const variant = codes.find(code => code.toLowerCase().startsWith(base + '-'));
      if (variant) return variant;
    }
  }
  return '';
}
